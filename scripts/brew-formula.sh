#!/bin/sh
# Prints the Homebrew formula for a release, for the Zenavo-App/homebrew-tap repository:
#
#   scripts/brew-formula.sh v0.2.0 dist/SHA256SUMS [base-url] > Formula/zenavo.rb
#
# The formula installs the release's own binaries, pinned by the checksums in SHA256SUMS. base-url defaults to the
# GitHub release of the tag; tests point it at local files.

set -eu

[ $# -ge 2 ] || {
	echo "usage: $0 <tag> <SHA256SUMS> [base-url]" >&2
	exit 2
}
tag=$1
sums=$2
base=${3:-https://github.com/Zenavo-App/zenavo-cli/releases/download/$tag}
case $tag in v[0-9]*) ;; *)
	echo "not a version tag: $tag" >&2
	exit 2
	;;
esac

sum() { # file
	s=$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1; exit }' "$sums")
	[ -n "$s" ] || {
		echo "$1 is not listed in $sums" >&2
		exit 1
	}
	echo "$s"
}

asset() { # os arch indent
	printf '%surl "%s/zenavo_%s_%s"\n' "$3" "$base" "$1" "$2"
	printf '%ssha256 "%s"\n' "$3" "$(sum "zenavo_$1_$2")"
}

cat <<EOF
# Generated by the zenavo-cli release workflow (scripts/brew-formula.sh); changes here are overwritten.
class Zenavo < Formula
  desc "Deploy and operate projects on your own servers with Zenavo"
  homepage "https://zenavo.app"
  version "${tag#v}"
  license "Apache-2.0"

  on_macos do
    on_arm do
$(asset darwin arm64 '      ')
    end
    on_intel do
$(asset darwin amd64 '      ')
    end
  end

  on_linux do
    on_arm do
$(asset linux arm64 '      ')
    end
    on_intel do
$(asset linux amd64 '      ')
    end
  end

  def install
    bin.install Dir["zenavo_*"].first => "zenavo"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/zenavo version")
  end
end
EOF
